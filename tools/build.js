// 12 Nights: builds the game from data/ (the editor's output).
//   node tools/build.js            -> writes game/shared/data.js only (for running tests from game/)
//   node tools/build.js dist        -> also makes dist/game: a full copy of the game with texts, colours, css and art applied
'use strict';
const fs = require('fs'), path = require('path');
const T = require('./transform.js');
const ROOT = path.join(__dirname, '..');
const DATA = path.join(ROOT, 'data'), GAME = path.join(ROOT, 'game');
const G = JSON.parse(fs.readFileSync(path.join(DATA, 'game.json'), 'utf8'));

function dataJs(g) {
  const d = Object.assign({}, g); delete d.texts; delete d.colors; delete d.css; delete d.colorsCss;
  return '// generated by tools/build.js from data/game.json. Edit data/game.json (or use the editor), not this file.\n' +
    '(function(root){const D=' + JSON.stringify(d) + ';if(typeof module!=="undefined")module.exports=D;else root.DATA=D;})(this);\n';
}
fs.writeFileSync(path.join(GAME, 'shared', 'data.js'), dataJs(G));
const out = process.argv[2];
if (out) {
  const dst = path.join(ROOT, out, 'game');
  fs.rmSync(dst, { recursive: true, force: true });
  const skip = new Set(['node_modules', 'test', 'tools']);
  (function copy(a, b) {
    fs.mkdirSync(b, { recursive: true });
    for (const n of fs.readdirSync(a)) {
      if (skip.has(n) && a === GAME) continue;
      const s = path.join(a, n), t = path.join(b, n);
      if (fs.statSync(s).isDirectory()) copy(s, t);
      else if (/\.(js|css|html)$/.test(n)) fs.writeFileSync(t, T.apply(fs.readFileSync(s, 'utf8'), n, G));
      else fs.copyFileSync(s, t);
    }
  })(GAME, dst);
  fs.writeFileSync(path.join(dst, 'shared', 'data.js'), dataJs(G));
  // art files uploaded in the editor
  const art = path.join(DATA, 'art');
  if (fs.existsSync(art)) (function copy(a, b) { fs.mkdirSync(b, { recursive: true }); for (const n of fs.readdirSync(a)) { const s = path.join(a, n); if (fs.statSync(s).isDirectory()) copy(s, path.join(b, n)); else fs.copyFileSync(s, path.join(b, n)); } })(art, path.join(dst, 'www', 'art'));
  fs.writeFileSync(path.join(dst, 'www', 'custom.css'), T.customCss(G, p => 'art/' + p));
  // version from the editor
  const pkg = JSON.parse(fs.readFileSync(path.join(dst, 'package.json'), 'utf8'));
  if (G.meta && G.meta.version) pkg.version = G.meta.version;
  fs.writeFileSync(path.join(dst, 'package.json'), JSON.stringify(pkg, null, 2));
  console.log('built', dst, 'version', pkg.version);
}
