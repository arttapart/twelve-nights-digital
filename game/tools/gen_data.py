def strip(t):
    t=t.strip()
    if t in ('ندارد','—',''): return None
    d={}
    for part in [p.strip() for p in t.split('+')]:
        if part=='گام ۱': d['step']=1
        elif part=='گام ۲': d['step']=2
        elif part=='دویدن': d['run']=1
        elif part=='تله‌پورت': d['tele']=1
        elif part=='چشم سوم': d['eye']=1
        elif part=='مشعل': d['ft']='t'
        elif part=='مشعل یا کلنگ': d['ft']='a'
        else: raise SystemExit('strip? '+part)
    return d
